-- 3. ROW LEVEL SECURITY: cada cliente accede solo a lo permitido.
alter table public.players enable row level security;
alter table public.doors enable row level security;
alter table public.plays enable row level security;

-- En esta actividad, los alias del ranking son públicos para participantes;
-- no se almacenan nombres completos ni información privada.
drop policy if exists players_read on public.players;
create policy players_read on public.players for select to authenticated
using (true);

drop policy if exists players_create_self on public.players;
create policy players_create_self on public.players for insert to authenticated
with check ((select auth.uid()) = id);

-- Casas visibles antes o después del inicio de sesión.
drop policy if exists doors_read on public.doors;
create policy doors_read on public.doors for select to anon, authenticated
using (active = true);

-- Solo se pueden leer jugadas desde un usuario autenticado.
-- No hay políticas para insertar/modificar/borrar jugadas desde el frontend.
-- Una función segura crea las jugadas, evitando alterar puntos manualmente.
drop policy if exists plays_read on public.plays;
create policy plays_read on public.plays for select to authenticated
using (true);

