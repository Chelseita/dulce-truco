-- 1. ENTIDADES Y RELACIONES
create table if not exists public.players (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(btrim(nickname)) between 2 and 20),
  created_at timestamptz not null default now()
);

create table if not exists public.doors (
  id integer generated by default as identity primary key,
  title text not null,
  emoji text not null,
  description text not null,
  active boolean not null default true
);

create table if not exists public.plays (
  id bigint generated always as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  door_id integer not null references public.doors(id),
  outcome text not null check (outcome in ('dulce','truco')),
  points integer not null check (points in (-10, -5, 5, 10, 15, 20)),
  created_at timestamptz not null default now(),
  constraint one_play_per_door unique (player_id, door_id),
  constraint consistent_reward check (
    (outcome = 'dulce' and points > 0) or
    (outcome = 'truco' and points < 0)
  )
);

create index if not exists idx_plays_player on public.plays (player_id);
create index if not exists idx_plays_created_at on public.plays (created_at desc);

