-- 4. VISTA: resultado del JOIN y GROUP BY para el ranking.
-- security_invoker respeta el RLS de tablas base (PostgreSQL 15+).
create or replace view public.leaderboard
with (security_invoker = true)
as
select
  p.id,
  p.nickname,
  coalesce(sum(g.points), 0)::integer as score,
  count(g.id)::integer as turns
from public.players as p
left join public.plays as g on g.player_id = p.id
group by p.id, p.nickname;

grant select on public.leaderboard to authenticated;

-- 5. FUNCIÓN DEL JUEGO.
-- Máximo 3 casas por usuario y ninguna casa se juega 2 veces.
-- Los puntos los calcula PostgreSQL; el frontend NO puede enviarlos.
create or replace function public.play_door(p_door_id integer)
returns table (
  door_name text,
  outcome text,
  points_earned integer,
  total_score integer,
  plays_used integer
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_door_name text;
  v_existing integer;
  v_outcome text;
  v_points integer;
  v_total integer;
  v_count integer;
begin
  if v_user is null then
    raise exception 'Debes ingresar al juego antes de abrir una casa.';
  end if;

  -- Serializa las jugadas del mismo usuario para hacer cumplir el límite,
  -- incluso si presiona rápidamente varios botones a la vez.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_user::text, 0)
  );

  if not exists (select 1 from public.players where id = v_user) then
    raise exception 'Primero registra tu apodo.';
  end if;

  select d.title into v_door_name
  from public.doors as d
  where d.id = p_door_id and d.active = true;
  if v_door_name is null then
    raise exception 'La casa indicada no está disponible.';
  end if;

  if exists (
    select 1 from public.plays
    where player_id = v_user and door_id = p_door_id
  ) then
    raise exception 'Ya visitaste esta casa; elige otra.';
  end if;

  select count(*)::integer into v_existing
  from public.plays where player_id = v_user;
  if v_existing >= 3 then
    raise exception 'Completaste tus 3 visitas. Mira el ranking final.';
  end if;

  -- 70% de probabilidad de dulce; 30% de truco.
  if pg_catalog.random() < 0.70 then
    v_outcome := 'dulce';
    v_points := (array[5, 10, 15, 20])[
      1 + pg_catalog.floor(pg_catalog.random() * 4)::integer
    ];
  else
    v_outcome := 'truco';
    v_points := (array[-5, -10])[
      1 + pg_catalog.floor(pg_catalog.random() * 2)::integer
    ];
  end if;

  insert into public.plays (player_id, door_id, outcome, points)
  values (v_user, p_door_id, v_outcome, v_points);

  select coalesce(sum(g.points), 0)::integer, count(*)::integer
  into v_total, v_count
  from public.plays as g
  where g.player_id = v_user;

  return query select v_door_name, v_outcome, v_points, v_total, v_count;
end;
$$;

revoke all on function public.play_door(integer) from public, anon;
grant execute on function public.play_door(integer) to authenticated;

